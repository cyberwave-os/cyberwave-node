/** Regeneration only touches the generated contract. Review schema updates separately. */
import openapiTS, { astToString } from 'openapi-typescript';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const schema = new URL('../schema/openapi.json', import.meta.url);
const extensions = new URL('../schema/extensions.openapi.json', import.meta.url);
// Development additions and selected path overrides stay separate from the pinned production API.
// Export from the backend's /api/v1/openapi.json; never hand-edit generated types.
const extensionSource = process.argv.find(arg => arg.startsWith('--extensions-from='))?.split('=').slice(1).join('=');
if (extensionSource) {
  const full = JSON.parse(await readFile(extensionSource, 'utf8'));
  const paths = Object.fromEntries(Object.entries(full.paths).filter(([path]) => /\/environments\/\{uuid\}\/(inspection-|missions$)/.test(path) || /\/workspaces\/\{workspace_uuid\}\/missions$/.test(path) || /\/workflows(?:$|\/\{uuid\}\/(?:input-contract|executions)$)/.test(path)));
  if (Object.keys(paths).length !== 9) throw new Error('Expected inspection, mission discovery, workflow input and pagination contracts');
  const schemas = {}, queue = [paths];
  while (queue.length) {
    const node = queue.shift();
    if (!node || typeof node !== 'object') continue;
    if (node.$ref?.startsWith('#/components/schemas/')) {
      const name = node.$ref.slice('#/components/schemas/'.length);
      if (!schemas[name]) { schemas[name] = full.components.schemas[name]; if (!schemas[name]) throw new Error(`Missing schema ${name}`); queue.push(schemas[name]); }
    }
    queue.push(...Object.values(node));
  }
  await writeFile(extensions, JSON.stringify({openapi:full.openapi,info:{title:'Cyberwave development extensions',version:'0.1.0-preview',description:'Development endpoints and workflow pagination overrides; deployment availability must be checked separately.'},paths,components:{schemas,securitySchemes:full.components.securitySchemes}},null,2)+'\n');
}
if (process.argv.includes('--refresh')) {
  const origin = process.env.CYBERWAVE_API_URL || 'https://api.cyberwave.com';
  const response = await fetch(new URL('/api/v1/openapi.json', origin), { signal: AbortSignal.timeout(30000), redirect: 'error' });
  if (!response.ok) throw new Error(`Schema download failed (${response.status})`);
  const json = await response.json();
  if (!json.openapi || !json.paths) throw new Error('Not an OpenAPI document');
  await writeFile(schema, JSON.stringify(json, null, 2) + '\n');
}
const bytes = await readFile(schema);
const source = astToString(await openapiTS(JSON.parse(bytes.toString())));
await writeFile(new URL('../src/generated/schema.ts', import.meta.url), '// Generated by openapi-typescript. Do not edit.\n' + source);
await writeFile(new URL('../schema/sha256.txt', import.meta.url), createHash('sha256').update(bytes).digest('hex') + '\n');
const extensionBytes = await readFile(extensions);
await writeFile(new URL('../src/generated/extensions.ts', import.meta.url), '// Generated by openapi-typescript. Do not edit.\n' + astToString(await openapiTS(JSON.parse(extensionBytes.toString()))));
await writeFile(new URL('../schema/extensions.sha256.txt', import.meta.url), createHash('sha256').update(extensionBytes).digest('hex') + '\n');
console.log('Generated the Cyberwave API contract from the pinned schema.');
